// Generates src/data/registry.ts from conformance/registry.json.
// The registry is frozen (ADR-0002, ADR-0015, ADR-0026); the site never
// edits it, only reads it. Run on every build so the two cannot drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../conformance/registry.json");
const dst = resolve(here, "../src/data/registry.ts");

const json = JSON.parse(readFileSync(src, "utf8"));
const entries = json.entries.map(({ slot, pattern, key, domain, rune }) => ({ slot, pattern, key, domain, rune }));

if (entries.length !== 24) throw new Error(`registry has ${entries.length} entries, expected 24`);

const out = `// GENERATED by scripts/sync-registry.mjs from conformance/registry.json. Do not edit.
// Schema: ${json.schema}

export type RegistryEntry = {
  slot: number;
  pattern: string;
  key: string;
  domain: string;
  /** Kernel-internal translation into the v1.0.0 order. Never a name, never an identity. */
  rune: number;
};

export const REGISTRY: readonly RegistryEntry[] = ${JSON.stringify(entries, null, 2)} as const;

/** Zero-padded slot number: 1 -> "01". */
export const slotLabel = (slot: number): string => String(slot).padStart(2, "0");

/** Slot tag format: a24-<slot>-<pattern-slug>, e.g. a24-03-do-san. */
export const slotTag = (slot: number): string => {
  const entry = REGISTRY[slot - 1];
  return \`a24-\${slotLabel(slot)}-\${entry.pattern.toLowerCase()}\`;
};

export const bySlot = (slot: number): RegistryEntry => REGISTRY[slot - 1];
`;

writeFileSync(dst, out);
console.log(`registry: wrote ${entries.length} entries to ${dst}`);
